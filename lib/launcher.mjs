/**
 * 「启动器」安装器 —— 让 npm / 插件市场装进来的人也能真正生效。
 *
 * 背景：体检（prelaunch）只有启动器会调用。没有启动器的人，面板永远是"还没有数据"，
 * 而且平时启动 DSH 也不会清理 cookie —— 等于装了没生效。
 *
 * 做法：在 %LOCALAPPDATA%\dsh-cookie431\ 生成一个 start-dsh.cmd（内容指向本包的
 * launcher/dsh-launch.cmd），再在桌面建一个快捷方式指向它。这样：
 *   - 包升级/换目录，只要这个 cmd 里的路径还有效就不影响；
 *   - 用户的桌面不再需要手抄命令。
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const PROJECT_ROOT = join(here, '..')

export const SHORTCUT_NAME = 'DSH（带体检启动）.lnk'

/** 安装目录：优先环境变量（测试用），否则 %LOCALAPPDATA%\dsh-cookie431 */
export function launcherDir() {
  if (process.env.CG_LAUNCHER_DIR) return process.env.CG_LAUNCHER_DIR
  const base = process.env.LOCALAPPDATA || join(homedir(), 'AppData', 'Local')
  return join(base, 'dsh-cookie431')
}

export function cmdPath(dir = launcherDir()) {
  return join(dir, 'start-dsh.cmd')
}

/** 桌面目录：允许用 CG_DESKTOP_DIR 覆盖（测试/非标准布局） */
export function desktopDir() {
  if (process.env.CG_DESKTOP_DIR) return process.env.CG_DESKTOP_DIR
  return join(homedir(), 'Desktop')
}

export function lnkPath() {
  return join(desktopDir(), SHORTCUT_NAME)
}

export function launcherStatus() {
  const cmd = cmdPath()
  const lnk = lnkPath()
  return {
    installed: existsSync(cmd),
    cmdPath: cmd,
    cmdExists: existsSync(cmd),
    lnkPath: lnk,
    lnkExists: existsSync(lnk),
  }
}

/** 生成 start-dsh.cmd 的内容（纯 ASCII + CRLF，cmd.exe 才认） */
export function buildCmd({ pkgRoot = PROJECT_ROOT, dshExe = '' } = {}) {
  const lines = [
    '@echo off',
    'rem Generated by dsh-cookie431 (DSH Cookie Guard). Safe to delete.',
    'rem It only forwards to the package launcher, so the logic stays in one place.',
    'setlocal EnableExtensions',
    `set "PKG=${pkgRoot}"`,
  ]
  if (dshExe) lines.push(`set "CG_DSH_EXE=${dshExe}"`)
  lines.push(
    `set "LOG=%LOCALAPPDATA%\\dsh-cookie431\\launcher.log"`,
    'if not exist "%PKG%\\launcher\\dsh-launch.cmd" goto :missing',
    'call "%PKG%\\launcher\\dsh-launch.cmd" %*',
    'exit /b %ERRORLEVEL%',
    '',
    ':missing',
    'echo.',
    'echo   Package not found: %PKG%',
    'echo   Reinstall dsh-cookie431, or run this file again from the panel.',
    'echo.',
    'pause',
    'exit /b 1',
    '',
  )
  return lines.join('\r\n')
}

function psQuote(s) {
  return `'${String(s).replace(/'/g, "''")}'`
}

/** 用 WScript.Shell 建 .lnk（不引入任何依赖） */
function createShortcut(lnk, target, workdir, icon) {
  const ps = [
    '$ws = New-Object -ComObject WScript.Shell',
    `$s = $ws.CreateShortcut(${psQuote(lnk)})`,
    `$s.TargetPath = ${psQuote(target)}`,
    `$s.WorkingDirectory = ${psQuote(workdir)}`,
    icon ? `$s.IconLocation = ${psQuote(icon + ',0')}` : '',
    `$s.Description = 'Start DSH with a cookie check (dsh-cookie431)'`,
    '$s.Save()',
  ].filter(Boolean).join('; ')
  const r = spawnSync('powershell', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', ps], {
    encoding: 'utf8',
    windowsHide: true,
  })
  return {
    ok: !r.error && r.status === 0,
    status: r.status,
    stderr: (r.stderr || '').trim(),
    error: r.error ? String(r.error.message ?? r.error) : null,
  }
}

/**
 * 安装启动器。
 * @param {object} [opts]
 * @param {boolean} [opts.dryRun]      只算出路径与内容，不落盘
 * @param {boolean} [opts.noShortcut]  只写 cmd，不建桌面快捷方式（测试用）
 * @param {boolean} [opts.force]       已存在同名快捷方式时也覆盖
 * @param {string}  [opts.dshExe]      DSH 的 exe 路径（宿主里就是 process.execPath）
 * @param {string}  [opts.pkgRoot]     包根目录（默认本包）
 */
export function installLauncher(opts = {}) {
  const { dryRun = false, noShortcut = false, force = false } = opts
  const pkgRoot = opts.pkgRoot ?? PROJECT_ROOT
  const dshExe = opts.dshExe ?? ''
  const dir = launcherDir()
  const cmd = cmdPath(dir)
  const lnk = lnkPath()
  const content = buildCmd({ pkgRoot, dshExe })

  const result = {
    ok: false,
    dryRun,
    cmdPath: cmd,
    lnkPath: lnk,
    lnkCreated: false,
    lnkSkipped: null,
    bytes: Buffer.byteLength(content, 'ascii'),
    content: dryRun ? content : undefined,
    notes: [],
  }

  if (dryRun) {
    result.ok = true
    result.notes.push('dry-run：没有写入任何文件')
    return result
  }

  mkdirSync(dir, { recursive: true })
  writeFileSync(cmd, content, { encoding: 'ascii' })

  if (noShortcut) {
    result.ok = true
    result.lnkSkipped = 'no-shortcut'
    return result
  }

  if (process.platform !== 'win32') {
    result.ok = true
    result.lnkSkipped = 'not-windows'
    return result
  }

  if (existsSync(lnk) && !force) {
    result.ok = true
    result.lnkSkipped = 'exists'
    result.notes.push('桌面上已经有同名快捷方式，保留了原来那个（要覆盖请加 --force）')
    return result
  }

  const icon = dshExe && existsSync(dshExe) ? dshExe : cmd
  const sc = createShortcut(lnk, cmd, dir, icon)
  result.lnkCreated = sc.ok
  result.ok = sc.ok || result.lnkSkipped === 'exists'
  if (!sc.ok) {
    result.error = sc.error || sc.stderr || `powershell exit ${sc.status}`
    result.notes.push('cmd 已生成，但桌面快捷方式没建成：' + result.error)
  }
  return result
}

/* ---------------- CLI ---------------- */
const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]

if (isCli) {
  const args = process.argv.slice(2)
  const has = (f) => args.includes(f)
  const val = (f, d) => {
    const i = args.indexOf(f)
    return i >= 0 && args[i + 1] ? args[i + 1] : d
  }
  // 宿主里 process.execPath 是 DSH 自己；命令行里跑就靠参数传
  const dshExe = val('--exe', has('--inside-dsh') ? process.execPath : '')
  const out = installLauncher({
    dryRun: has('--dry-run'),
    noShortcut: has('--no-shortcut'),
    force: has('--force'),
    dshExe,
  })
  if (has('--json')) {
    console.log(JSON.stringify(out, null, 2))
  } else if (out.dryRun) {
    console.log('将写入: ' + out.cmdPath)
    console.log('--------- 内容 ---------')
    console.log(out.content)
  } else {
    console.log('启动器已安装: ' + out.cmdPath)
    console.log(out.lnkCreated ? '桌面快捷方式: ' + out.lnkPath : '桌面快捷方式: 跳过（' + (out.lnkSkipped || '?') + '）')
    for (const n of out.notes) console.log('· ' + n)
  }
  process.exit(out.ok ? 0 : 1)
}
